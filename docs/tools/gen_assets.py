# -*- coding: utf-8 -*-
"""Generate the on-flash UI assets (avatar bitmap + marquee dot matrix strip).

The marquee strip is rendered from the same u8g2 wqy12 font that the firmware
uses, so the pixels are identical to what u8g2 would draw - it just lives in
flash so that the whole 328 px sentence can be shifted smoothly on a 128 px
screen (u8g2 itself clips at x<0).

Run:  python gen_assets.py      (writes ../Core/Src/ui_assets.c and previews)
"""
import os
import sys

from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, HERE)
from u8g2font import Font  # noqa: E402

FONT_PATH = os.path.join(ROOT, 'Middlewares', 'u8g2', 'fonts', 'u8g2_font_wqy12_cn.c')
OUT_C = os.path.join(ROOT, 'Core', 'Src', 'ui_assets.c')
OUT_H = os.path.join(ROOT, 'Core', 'Inc', 'ui_assets.h')
IMG_DIR = os.path.join(ROOT, 'docs', 'images')
MARQUEE = '你好,欢迎来到重庆交通大学物联网205实训室!'

os.makedirs(IMG_DIR, exist_ok=True)


# --------------------------------------------------------------------------
# 64x64 cartoon avatar (boy with glasses) - 1bpp, LSB = leftmost pixel
# --------------------------------------------------------------------------
def make_avatar():
    W = H = 64
    im = Image.new('1', (W, H), 0)
    d = ImageDraw.Draw(im)

    # shoulders / shirt
    d.rounded_rectangle([4, 56, 60, 70], radius=8, fill=1)
    d.rectangle([27, 43, 37, 58], fill=1)

    # hair (white, slightly wider than the head)
    d.ellipse([15, 7, 49, 31], fill=1)
    d.polygon([(15, 24), (12, 14), (18, 16), (20, 8), (25, 15),
               (30, 5), (33, 14), (40, 7), (42, 16), (48, 12), (49, 24)], fill=1)

    # head + ears
    d.ellipse([18, 14, 46, 51], fill=1)
    d.ellipse([15, 31, 20, 39], fill=1)
    d.ellipse([44, 31, 49, 39], fill=1)

    # fringe: black jagged line separating hair and forehead
    d.line([(17, 27), (19, 24), (22, 28), (25, 24), (28, 27), (31, 23),
            (34, 27), (37, 24), (40, 28), (43, 24), (45, 27)], fill=0, width=2)
    d.line([(18, 28), (18, 33)], fill=0, width=2)
    d.line([(46, 28), (46, 33)], fill=0, width=2)

    # glasses
    d.rectangle([20, 31, 30, 39], outline=0, width=1)
    d.rectangle([34, 31, 44, 39], outline=0, width=1)
    d.line([(30, 34), (34, 34)], fill=0)
    d.line([(20, 33), (17, 33)], fill=0)
    d.line([(44, 33), (47, 33)], fill=0)
    d.rectangle([23, 34, 24, 36], fill=0)
    d.rectangle([39, 34, 40, 36], fill=0)

    # nose / mouth
    d.line([(32, 40), (32, 43)], fill=0)
    d.point((31, 43), fill=0)
    d.arc([26, 40, 38, 50], start=25, end=155, fill=0, width=1)

    # collar
    d.line([(24, 52), (32, 60), (40, 52)], fill=0)

    bits = [[1 if im.getpixel((x, y)) else 0 for x in range(W)] for y in range(H)]
    rows = []
    for y in range(H):
        row = []
        for xb in range(0, W, 8):
            b = 0
            for bit in range(8):
                if bits[y][xb + bit]:
                    b |= 1 << bit
            row.append(b)
        rows.append(row)
    im.convert('L').resize((W * 6, H * 6), Image.NEAREST).save(
        os.path.join(IMG_DIR, 'avatar_preview.png'))
    return rows


# --------------------------------------------------------------------------
# marquee strip: 16 px tall, page-major bytes (2 bytes per column)
# --------------------------------------------------------------------------
def make_marquee():
    font = Font(FONT_PATH)
    width = font.width(MARQUEE)
    canvas = __import__('u8g2font').Canvas(width, 16)
    font.draw(canvas, 0, 14, MARQUEE)   # baseline 14 -> ink occupies rows 0..15
    strip = []
    for x in range(width):
        b0 = b1 = 0
        for bit in range(8):
            if canvas.px[bit][x]:
                b0 |= 1 << bit
            if canvas.px[bit + 8][x]:
                b1 |= 1 << bit
        strip += [b0, b1]
    # preview: strip on screen-sized canvas
    prev = Image.new('L', (width, 16), 0)
    prev.putdata([255 if v else 0 for row in canvas.px for v in row])
    prev.resize((width * 2, 32), Image.NEAREST).save(os.path.join(IMG_DIR, 'marquee_strip.png'))
    return width, strip


def write_c(avatar_rows, marq_w, strip):
    with open(OUT_C, 'w', encoding='utf-8') as f:
        f.write('/* Auto-generated by docs/tools/gen_assets.py - do not edit by hand. */\n')
        f.write('#include "ui_assets.h"\n\n')
        f.write('/* 64x64 1-bit avatar, 8 bytes per row, LSB = leftmost pixel */\n')
        f.write('const uint8_t ui_avatar_64x64[512] = {\n')
        for y, row in enumerate(avatar_rows):
            f.write('  ' + ', '.join('0x%02X' % b for b in row) +
                    (',' if y != 63 else '') + '  /* row %2d */\n' % y)
        f.write('};\n\n')
        f.write('/* Marquee dot matrix: %d px wide, 16 px high, page-major (2 bytes/column) */\n' % marq_w)
        f.write('const uint16_t ui_marquee_width = %dU;\n' % marq_w)
        f.write('const uint8_t ui_marquee_strip[%d] = {\n' % len(strip))
        for i in range(0, len(strip), 16):
            chunk = strip[i:i + 16]
            f.write('  ' + ', '.join('0x%02X' % b for b in chunk) +
                    (',' if i + 16 < len(strip) else '') + '\n')
        f.write('};\n')

    with open(OUT_H, 'w', encoding='utf-8') as f:
        f.write('#ifndef UI_ASSETS_H\n#define UI_ASSETS_H\n\n#include <stdint.h>\n\n')
        f.write('extern const uint8_t ui_avatar_64x64[512];\n')
        f.write('extern const uint16_t ui_marquee_width;\n')
        f.write('extern const uint8_t ui_marquee_strip[%d];\n\n' % len(strip))
        f.write('#endif /* UI_ASSETS_H */\n')


if __name__ == '__main__':
    a = make_avatar()
    w, s = make_marquee()
    write_c(a, w, s)
    print('avatar 64x64, marquee %dpx = %d bytes, total flash %d bytes' % (w, len(s), 512 + len(s)))
