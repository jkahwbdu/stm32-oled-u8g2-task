# -*- coding: utf-8 -*-
"""Generate Core/Inc/ui_text.h: the Chinese UI strings as exact UTF-8 escapes.

Keil/ARMCC V5 reads source files with the Windows ANSI code page (GBK on this
machine), so a UTF-8 literal such as "蒋俊熙" is mis-decoded and can even eat
the closing quote.  Keeping the C sources ASCII-only and writing the text as
\\xHH byte escapes is portable and still delivers proper UTF-8 to u8g2.

The real text lives here (UTF-8) - run this script after changing it.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.abspath(os.path.join(HERE, '..', '..', 'Core', 'Inc', 'ui_text.h'))

TEXTS = [
    ('UI_TXT_NAME',    '蒋俊熙',   'student name'),
    ('UI_TXT_TEMP',    '温度',     'temperature label'),
    ('UI_TXT_HUM',     '湿度',     'humidity label'),
    ('UI_TXT_ROOM',    '物联网205', 'lab room, shown on the marquee page'),
    ('UI_TXT_POEM0',   '床前明月光', 'poem line 1'),
    ('UI_TXT_POEM1',   '疑是地上霜', 'poem line 2'),
    ('UI_TXT_POEM2',   '举头望明月', 'poem line 3'),
    ('UI_TXT_POEM3',   '低头思故乡', 'poem line 4'),
]


def esc(s):
    parts = []
    for b in s.encode('utf-8'):
        if 0x20 <= b < 0x7f and b not in (0x22, 0x5c):
            parts.append(chr(b))
        else:
            parts.append('\\x%02X' % b)
    # a \xHH escape must not run into a following hex digit (e.g. \x91205)
    out = ''
    for i, p in enumerate(parts):
        if i > 0 and p[0] in '0123456789abcdefABCDEF' and parts[i - 1].startswith('\\x'):
            out += '" "'
        out += p
    return '"' + out + '"'


def main():
    lines = [
        '/* Auto-generated by docs/tools/gen_text.py - do not edit by hand.',
        ' * UTF-8 byte escapes keep the C sources ASCII-only (ARMCC reads GBK).',
        ' * The readable text of each string is kept in gen_text.py. */',
        '#ifndef UI_TEXT_H',
        '#define UI_TEXT_H',
        '',
    ]
    for name, text, note in TEXTS:
        lines.append('#define %-12s %s  /* %s */' % (name, esc(text), note))
    lines += ['', '#endif /* UI_TEXT_H */', '']
    src = '\n'.join(lines)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(src)
    print('wrote', OUT, len(TEXTS), 'strings')


if __name__ == '__main__':
    main()
